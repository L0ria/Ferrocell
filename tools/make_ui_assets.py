#!/usr/bin/env python3
"""Regenerate ferrocell/src/net/ui_assets.h from ferrocell/data/ (M5, #6).

The web UI (index.html + ui.css + ui.js) is embedded into PROGMEM as C byte
arrays so UiServer can serve it from flash (no filesystem / SPIFFS needed).
This script is the single source of truth for that embedding.

Usage:
    python3 tools/make_ui_assets.py

It reads ferrocell/data/{index.html,ui.css,ui.js} and writes
ferrocell/src/net/ui_assets.h. Re-run it whenever the assets change, then
rebuild (./build.sh). The generated header is committed so the firmware build
is reproducible without a Python step.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "ferrocell", "data")
OUT = os.path.join(ROOT, "ferrocell", "src", "net", "ui_assets.h")

# (symbol, file, mime)
ASSETS = [
    ("kIndexHtml", "index.html", "text/html"),
    ("kUiCss", "ui.css", "text/css"),
    ("kUiJs", "ui.js", "application/javascript"),
]


def main() -> int:
    out = []
    out.append("// AUTO-GENERATED by tools/make_ui_assets.py from ferrocell/data/ — do not edit by hand.")
    out.append("// Embeds the self-contained web UI into PROGMEM for UiServer (M5, issue #6).")
    out.append("#pragma once")
    out.append("#include <Arduino.h>")

    for name, fn, mime in ASSETS:
        path = os.path.join(DATA, fn)
        if not os.path.isfile(path):
            print(f"error: missing asset {path}", file=sys.stderr)
            return 1
        with open(path, "rb") as f:
            data = f.read()
        out.append("")
        out.append(f"// {fn} ({len(data)} bytes, {mime})")
        out.append(f"static const char {name}[] PROGMEM = {{")
        line = []
        for i, b in enumerate(data):
            line.append(str(b))
            if (i + 1) % 16 == 0:
                out.append("  " + ",".join(line) + ",")
                line = []
        if line:
            out.append("  " + ",".join(line))
        out.append("};")
        out.append(f"static const size_t {name}Len = {len(data)};")
        out.append(f"static const char {name}Mime[] = \"{mime}\";")

    with open(OUT, "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {os.path.relpath(OUT, ROOT)} ({os.path.getsize(OUT)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
